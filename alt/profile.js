// **ข้อมูลดิบมีอยู่ในเครื่องครบแล้วตั้งแต่ต้น** — `state.sessions` เก็บทุกรอบจับเวลา
// พร้อมเวลาเริ่มและจำนวนนาที ส่วน `context.js` บอกได้ว่าวันนั้นมีช่องว่างตรงไหนบ้าง
// เอาสองอย่างมาหารกันก็ได้คำตอบของคำถามที่ FOLLOW_RATE_PRIOR เดาไว้แทนมาตลอด:
// "เวลาว่างบนปฏิทิน 100 นาที กลายเป็นเวลาที่ได้ทำงานจริงกี่นาที"
//
// ที่ผ่านมาข้อมูลชุดนี้ถูกใช้พิมพ์เป็นเกร็ดน่ารู้ในหน้าสรุปสัปดาห์แล้วจบ
// ไม่เคยไหลเข้าสู่การตัดสินใจเลยสักครั้ง
