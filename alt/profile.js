// ---------- ขอบเขตที่มองย้อนหลัง ----------
// 21 วันพอจะเห็นนิสัย แต่ไม่ไกลจนติดนิสัยของเทอมที่แล้ว
// (และ SESSION_CAP ใน app.js เก็บไว้แค่ 50 รอบอยู่แล้ว ยาวกว่านี้ก็ไม่มีข้อมูลให้อ่าน)
const PROFILE_DAYS = 21;

// ต้องมีวันที่ "มีช่องว่างจริง" อย่างน้อยเท่านี้ถึงจะเริ่มเชื่อ
const PROFILE_MIN_DAYS = 5;

// น้ำหนักของค่ากลาง วัดเป็นจำนวนวัน — ข้อมูล 6 วันแรกถูกถ่วงด้วยค่ากลางครึ่งต่อครึ่ง
//
// ไม่มีตัวนี้แล้วจะเกิดอาการที่แย่ที่สุดของการเรียนรู้จากข้อมูลน้อย:
// ป่วยนอนสองวัน อัตราลงมือร่วงเหลือ 0.1 แล้วทั้งแอปประกาศว่าทุกงานไม่ทัน
// พอหายป่วยทำรวดเดียวสี่ชั่วโมง อัตราพุ่งเป็น 1.0 แล้วทุกงานกลายเป็นสบายหมด
// ตัวเลขที่แกว่งแบบนั้นแย่กว่าค่ากลางที่นิ่ง เพราะมันทำให้คนเลิกเชื่อทั้งระบบ
const PROFILE_SHRINK = 6;

// ---------- เพดานกับพื้นของอัตราที่ยอมให้เรียนรู้ได้ ----------
// ต่ำกว่า 0.35 แทบจะแปลว่า "ทำแต่ไม่ได้กดจับเวลา" ไม่ใช่ "ว่างแล้วไม่ทำ" —
// ปล่อยให้ต่ำกว่านี้ได้เมื่อไหร่ แอปจะขึ้นเตือนสีแดงทั้งจอให้กับคนที่จริง ๆ แล้วทำงานทัน
// ส่วนเพดาน 0.95 กันไม่ให้เชื่อว่ามีใครใช้เวลาว่างได้เต็มร้อย ซึ่งไม่เคยเกิดกับใคร
//
// ผลพลอยได้: สิ่งที่ไฟล์นี้วัดได้แม่นที่สุดจึงไม่ใช่ระดับของอัตรา แต่เป็น **ลำดับของช่วงเวลา**
// ("ค่ำดีกว่าเช้า") ซึ่งไม่ขึ้นกับว่าเขากดปุ่มบ่อยแค่ไหน เพราะเขากดหรือไม่กดพอ ๆ กันทุกช่วง
const RATE_FLOOR = 0.35;
const RATE_CEIL = 0.95;

// ---------- ช่วงของวัน ----------
// สามช่วงพอ ไม่ใช่ 24 ช่อง — เก็บได้แค่ 50 รอบจับเวลา แบ่ง 24 ช่องแล้วแต่ละช่องเหลือสองรอบ
// ซึ่งไม่พอจะสรุปอะไร · สามช่วงนี้ตรงกับที่ชีวิตเด็กมัธยมแบ่งจริง (ก่อนไปเรียน / เย็น / ก่อนนอน)
const PROFILE_BUCKETS = [
  { from: 0,  to: 12, name: 'เช้า' },
  { from: 12, to: 17, name: 'บ่าย' },
  { from: 17, to: 24, name: 'ค่ำ' },
];

function profileBucketOf(hour) {
  for (let i = 0; i < PROFILE_BUCKETS.length; i++) {
    if (hour >= PROFILE_BUCKETS[i].from && hour < PROFILE_BUCKETS[i].to) return i;
  }
  return PROFILE_BUCKETS.length - 1;
}

// ถ่วงค่าที่วัดได้กับค่ากลาง ตามปริมาณหลักฐานที่มี
function profileShrink(observed, n, prior) {
  if (!n) return prior;
  return (observed * n + prior * PROFILE_SHRINK) / (n + PROFILE_SHRINK);
}

// ---------- ตัวหลัก ----------
// นับสองอย่างต่อวัน แล้วเอามาหารกัน:
//   free   — ช่องว่างที่ปฏิทินบอกว่ามี (จาก context.js)
//   worked — นาทีที่กดจับเวลาจริง (จาก state.sessions)
//
// ข้อจำกัดที่รู้ตัว: freeSlots() ของวันย้อนหลังคำนวณจาก **ตารางเรียนปัจจุบัน**
// ถ้าเพิ่งเปลี่ยนตาราง ตัวเลขของวันก่อนหน้าจะเพี้ยนไปบ้าง · ยอมรับได้เพราะ
// ทางเลือกอื่นคือเก็บ snapshot ของตารางทุกวัน ซึ่งแพงกว่าประโยชน์ที่ได้มาก
function studyProfile(state, now = new Date()) {
  const prior = typeof FOLLOW_RATE_PRIOR === 'number' ? FOLLOW_RATE_PRIOR : 0.7;
  const blank = {
    rate: prior, learned: false, days: 0, workedMin: 0, freeMin: 0,
    buckets: PROFILE_BUCKETS.map(b => ({ name: b.name, rate: prior, days: 0, learned: false })),
    bestBucket: null, medianRun: null,
  };
  if (!state || !Array.isArray(state.sessions) || typeof freeSlots !== 'function') return blank;

  // ---- รวมนาทีที่ทำจริง แยกตามวันและช่วง ----
  const worked = {};          // 'YYYY-M-D' -> [เช้า, บ่าย, ค่ำ]
  const runs = [];
  const since = new Date(now.getTime() - PROFILE_DAYS * 864e5);
  for (const s of state.sessions) {
    const st = new Date(s.start);
    if (isNaN(st) || st < since || st > now) continue;
    const key = st.getFullYear() + '-' + st.getMonth() + '-' + st.getDate();
    const arr = worked[key] || (worked[key] = [0, 0, 0]);
    arr[profileBucketOf(st.getHours())] += s.min || 0;
    if (s.min >= 5) runs.push(s.min);
  }

  // ---- รวมช่องว่างที่ปฏิทินบอกว่ามี แยกแบบเดียวกัน ----
  // นับเฉพาะ "วันที่ผ่านไปแล้วทั้งวัน" — วันนี้ยังไม่จบ เอามาหารจะได้อัตราต่ำปลอม ๆ เสมอ
  let days = 0, totFree = 0, totWork = 0;
  const bFree = [0, 0, 0], bWork = [0, 0, 0], bDays = [0, 0, 0];

  for (let i = 1; i <= PROFILE_DAYS; i++) {
    const d = new Date(now); d.setDate(d.getDate() - i);
    const key = d.getFullYear() + '-' + d.getMonth() + '-' + d.getDate();
    const w = worked[key] || [0, 0, 0];

    const free = [0, 0, 0];
    for (const sl of freeSlots(d)) {
      // ช่วงที่คร่อมเส้นแบ่งถูกนับให้ช่วงที่มันเริ่ม — ไม่คุ้มจะหั่นให้ละเอียดกว่านี้
      free[profileBucketOf(Math.floor(sl.from / 60))] += sl.min;
    }
    const dayFree = free[0] + free[1] + free[2];
    if (dayFree < 30) continue;      // วันที่แทบไม่มีช่องว่าง ไม่ได้บอกอะไรเรื่องนิสัย

    // ---- วันที่ไม่มีรอบจับเวลาเลย = ไม่มีข้อมูล ไม่ใช่ "วันที่ไม่ได้ทำงาน" ----
    //
    // นี่คือบั๊กที่แพงที่สุดของไฟล์นี้ และเจอตอนทดสอบ: เครื่องที่ไม่เคยกดจับเวลาเลยสักครั้ง
    // ได้ learned: true พร้อม rate 0.16 — แล้วแอปก็ประกาศว่าทุกงานไม่ทันตั้งแต่วันแรก
    //
    // การจับเวลาเป็นของที่กดหรือไม่กดก็ได้ในแอปนี้ · งานส่วนใหญ่เกิดขึ้นโดยไม่มีใครกดปุ่ม
    // ความเงียบจึงแปลได้สองอย่าง ("ไม่ได้ทำ" กับ "ทำแต่ไม่ได้กด") และเราแยกไม่ออก
    // เมื่อแยกไม่ออก ต้องไม่นับ — ไม่ใช่เดาข้างใดข้างหนึ่ง
    if (w[0] + w[1] + w[2] <= 0) continue;

    days++;
    totFree += dayFree;
    totWork += w[0] + w[1] + w[2];
    for (let b = 0; b < 3; b++) {
      if (free[b] < 20) continue;
      bDays[b]++; bFree[b] += free[b]; bWork[b] += w[b];
    }
  }

  if (days < PROFILE_MIN_DAYS) return blank;

  // ทำเกินเวลาว่างได้จริง (ยืมเวลานอน) แต่ในฐานะ "ตัวคูณของช่องว่าง" ต้องไม่เกิน 1
  // ไม่งั้นตัวจำลองจะเชื่อว่าช่องว่าง 60 นาทีให้งานได้ 80 นาที ซึ่งไม่ใช่สิ่งที่ตัวเลขนี้แปลว่าอะไร
  const clamp = v => Math.max(RATE_FLOOR, Math.min(RATE_CEIL, v));
  const rate = clamp(profileShrink(totWork / totFree, days, prior));

  const buckets = PROFILE_BUCKETS.map((b, i) => ({
    name: b.name,
    rate: bDays[i] ? clamp(profileShrink(bWork[i] / bFree[i], bDays[i], prior)) : prior,
    days: bDays[i],
    learned: bDays[i] >= PROFILE_MIN_DAYS,
  }));

  // ช่วงที่ลงมือได้ดีที่สุด — บอกก็ต่อเมื่อมันดีกว่าช่วงอื่นอย่างเห็นได้ชัดจริง ๆ
  // ต่างกันไม่ถึงสิบเปอร์เซ็นต์ไม่ใช่ข้อมูล มันคือเสียงรบกวนที่ถูกเอาไปเขียนเป็นประโยค
  const usable = buckets.map((b, i) => ({ ...b, i })).filter(b => b.learned);
  usable.sort((a, b) => b.rate - a.rate);
  const bestBucket = (usable.length >= 2 && usable[0].rate - usable[1].rate >= 0.1)
    ? usable[0] : null;

  // รอบจับเวลาปกติยาวแค่ไหน — ใช้ค่ากลาง ไม่ใช่ค่าเฉลี่ย เพราะรอบเดียวที่ยาวสามชั่วโมง
  // ลากค่าเฉลี่ยขึ้นทั้งชุด ทั้งที่ไม่ได้เกิดบ่อย
  runs.sort((a, b) => a - b);
  const medianRun = runs.length >= 5 ? runs[Math.floor(runs.length / 2)] : null;

  return { rate, learned: true, days, workedMin: totWork, freeMin: totFree,
    buckets, bestBucket, medianRun };
}

// ประโยคเดียวที่เอาไปโชว์ได้ — คืน null เมื่อยังไม่รู้จริง ตามกติกาข้อ 1
function profileText(p) {
  if (!p || !p.learned) return null;
  const pct = Math.round(p.rate * 100);
  const base = 'จาก ' + p.days + ' วันที่ผ่านมา เวลาว่างของคุณกลายเป็นเวลาทำงานจริงราว ' + pct + '%';
  return p.bestBucket
    ? base + ' · ช่วง' + p.bestBucket.name + 'คุณลงมือได้ดีที่สุด'
    : base;
}
