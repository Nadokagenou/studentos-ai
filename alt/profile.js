//
//   1. เงียบจนกว่าจะรู้จริง — ข้อมูลไม่ถึงเกณฑ์ ให้ถอยไปใช้ค่ากลาง ไม่ใช่เดาสุ่ม
//   2. ค่อย ๆ เชื่อ ไม่เชื่อทันที — สามวันแรกไม่ใช่นิสัย มันคือสามวัน
//   3. ทุกอย่างอยู่ในเครื่อง ไม่มีข้อมูลไหนถูกส่งไปให้ใครวิเคราะห์
