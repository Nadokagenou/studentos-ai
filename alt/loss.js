// พอมีหน่วยแล้ว คำถามที่ตอบไม่ได้มาตลอดก็ตอบได้ทันที:
// "เลือกทางนี้แทนทางนั้น ต่างกันเท่าไหร่" — ตอบว่า 2.3 คะแนนของทั้งเทอม
