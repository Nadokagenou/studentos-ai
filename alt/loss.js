//   GradeLoss      คะแนนที่เสียจากงานที่ทำไม่ทัน — ก้อนที่ชัดที่สุด
//   KnowledgeDebt  หนี้ความรู้ที่วิชาสะสมทบไปข้างหน้า — ก้อนที่ทำให้มันเป็น "ที่ปรึกษา"
//   StressCost     ยกกำลัง เพราะห้าชั่วโมงคืนเดียวไม่เท่ากับหนึ่งชั่วโมงห้าคืน
//   SleepDebt      เวลาที่ยืมมาจากการนอน — ราคาที่แผนส่วนใหญ่แอบไม่คิด
//
// **ค่าคงที่ในไฟล์นี้คือที่เดียวที่ยังต้องตั้งด้วยวิจารณญาณ** และมันถูกรวบมาไว้ที่เดียวโดยตั้งใจ
// เฟส 5 (สอบเทียบ) จะเป็นตัวบอกว่าตั้งไว้ถูกไหม — จนกว่าจะถึงตอนนั้น อย่าไปขยับมันตามความรู้สึก
