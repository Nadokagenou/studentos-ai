// ไม่ใช่ชั่วโมงที่จะขาด ไม่ใช่ความน่าจะเป็น แปลว่าไม่มีทางพิสูจน์ว่าคำแนะนำเมื่อวานถูกหรือผิด
// และของที่ผิดไม่ได้ ก็เก่งขึ้นอย่างเป็นระบบไม่ได้ ทำได้อย่างเดียวคือรอเจอเคสพังแล้วขยับเลข
