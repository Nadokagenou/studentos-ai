// ---------- น้ำหนักของงานที่ไม่รู้คะแนน ----------
// "ครูไม่ได้บอกว่ากี่คะแนน" เป็นกรณีปกติของนักเรียน ไม่ใช่สัญญาณว่างานไม่สำคัญ
// engine.js ตัดสินเรื่องเดียวกันนี้ไปแล้วด้วยการให้ค่ากลาง ~12% — ใช้ตัวเลขเดียวกันไว้ก่อน
// ให้ 0 เมื่อไหร่ งานที่ไม่รู้คะแนนจะหายไปจากการตัดสินใจทั้งหมด ซึ่งผิดแน่นอน
const LOSS_DEFAULT_WEIGHT = 8;

// ---------- วิชาที่ความรู้ทบต้น ----------
// ไม่อ่านฟิสิกส์บทนี้ ไม่ได้เสียแค่คะแนนสอบครั้งนี้ — มันทำให้อีกสามบทข้างหน้าอ่านยากขึ้น
// ที่ปรึกษาที่เก่งปกป้องอีกสามเดือนข้างหน้า ไม่ใช่ปกป้องแค่คืนนี้
//
// วิชาที่แยกเป็นหน่วยจบในตัว (ประวัติศาสตร์ · ศิลปะ · การงาน) ไม่มีหนี้ก้อนนี้ —
// พลาดบทหนึ่งไม่ได้ทำให้บทถัดไปยากขึ้น · การให้ทุกวิชาเท่ากันคือการทิ้งข้อมูลที่มีอยู่แล้วทิ้ง
const CUMULATIVE_SUBJECTS = [
  'คณิตศาสตร์', 'ฟิสิกส์', 'เคมี', 'ชีววิทยา', 'วิทยาศาสตร์',
  'ภาษาอังกฤษ', 'ภาษาไทย', 'วิทยาการคำนวณ',
];
function isCumulative(subject) { return CUMULATIVE_SUBJECTS.includes((subject || '').trim()); }

// ดอกเบี้ยของหนี้ความรู้ — 0.35 หมายถึง "พลาดหน่วยนี้ไป ทำให้หน่วยข้างหน้าแพงขึ้นอีกราวหนึ่งในสาม
// ของน้ำหนักหน่วยนี้" · เป็นตัวเลขที่ตั้งจากวิจารณญาณ ไม่ได้วัดมา และรู้ตัวว่าไม่ได้วัด
const DEBT_RATE = 0.35;

// ---------- ราคาของความแน่น ----------
// ยกกำลัง 2.5 คือที่มาทั้งหมดของคำว่า "ควรเริ่มก่อน" — และเป็นเหตุผลที่ไม่ต้องเขียนกฎนั้นลงไปเลย
//   วันละ 2 ชม. ห้าวัน   → 5 × 1^2.5   = 5
//   สิบชั่วโมงในวันเดียว  → 1 × 5^2.5   = 55.9
// งานก้อนเดียวกัน เวลารวมเท่ากัน แต่แพงกว่ากันสิบเอ็ดเท่า ซึ่งตรงกับความรู้สึกจริงของคนทำ
//
// **ตัวหารต้องเป็นเวลาที่นั่งทำไหวต่อวัน ไม่ใช่ความจุของวันนั้น** — จุดนี้เคยทำผิดมาแล้ว
// ตอนแรกใช้ load/cap ซึ่งแปลว่า "ว่าง 30 นาทีแล้วทำครบ 30 นาที" แน่นเท่ากับ
// "ว่าง 5 ชั่วโมงแล้วทำครบ 5 ชั่วโมง" ทั้งที่คนละเรื่องกันโดยสิ้นเชิง
// ผลที่วัดได้จริง: เอนจินแนะนำให้ "ไม่ต้องทำอะไรคืนนี้" ทุกครั้งที่ช่วงว่างสั้น
// เพราะการใช้ช่วงสั้นให้เต็มถูกคิดราคาเท่ากับการอัดทั้งวัน — ซึ่งเป็นกับดักผัดวันประกันพรุ่ง
// ที่แอปนี้ตั้งใจจะแก้ ไม่ใช่ตั้งใจจะสอน
const SUSTAINABLE_MIN = 120;
const STRESS_EXP = 2.5;
const LAMBDA_STRESS = 0.4;

// ---------- ราคาของการยืมเวลานอน ----------
// หนึ่งชั่วโมงที่ยืมมา = 1.2 คะแนนเทอม · แพงพอที่แผนซึ่งรอดได้ด้วยการอดนอนจะแพ้เสมอ
// เมื่อมีทางอื่น แต่ไม่แพงจนแอปห้ามอดนอนในคืนที่มันคือทางเดียวที่เหลือจริง ๆ
const LAMBDA_SLEEP = 0.02;

// ---------- ได้คะแนนเท่าไหร่เมื่อทำไม่ครบ ----------
// การบ้าน/รายงาน: ส่งไปหกสิบเปอร์เซ็นต์ ก็ได้ราวหกสิบเปอร์เซ็นต์ — ตรงไปตรงมา
//
// สอบ: ต่างกันโดยสิ้นเชิง เพราะ "ทำไม่ครบ" ของสอบแปลว่า "อ่านไม่ครบ" ไม่ใช่ "ส่งไม่ครบ"
// ไม่อ่านเลยก็ยังทำได้บ้างจากที่เรียนในห้อง (ตั้งไว้ที่ 35%) แล้วที่เหลือค่อยไต่ขึ้นตามที่อ่าน
// ถ้าใช้เส้นตรงเหมือนการบ้าน แบบจำลองจะเชื่อว่าไม่อ่านเลย = ได้ศูนย์ ซึ่งไม่จริง
// และจะทำให้การอ่านสอบชนะทุกอย่างบนจอตลอดเวลา
const EXAM_FLOOR = 0.35;
function scoreFraction(frac, type) {
  const f = Math.max(0, Math.min(1, frac));
  return type === 'exam' ? EXAM_FLOOR + (1 - EXAM_FLOOR) * f : f;
}

function weightOf(item) {
  return item.scorePct != null ? item.scorePct : LOSS_DEFAULT_WEIGHT;
}

// ---------- ตีราคาอนาคตหนึ่งเส้น ----------
// รับผลจาก simRollout() ตรง ๆ · ไม่มีการสุ่มในไฟล์นี้เลย เป็นฟังก์ชันบริสุทธิ์ล้วน
// ใส่ frac ชุดเดิมต้องได้ตัวเลขเดิมทุกครั้ง — ทดสอบง่าย และเถียงกับใครไม่ได้
function lossOf(prep, out) {
  let grade = 0, debt = 0;
  const perTask = [];

  for (let i = 0; i < prep.items.length; i++) {
    const it = prep.items[i];
    const w = weightOf(it);
    const f = out.frac[i];
    const got = scoreFraction(f, it.type);
    const g = w * (1 - got);
    const d = isCumulative(it.subject) ? w * DEBT_RATE * (1 - f) : 0;
    grade += g;
    debt += d;
    perTask.push({ idx: i, frac: f, gradeLoss: g, debt: d, done: f >= 0.999 });
  }

  // ความแน่นรายวัน — วัดจากจำนวนนาทีที่นั่งทำจริง เทียบกับที่คนนั่งทำไหวต่อวัน
  // ความเหนื่อยมาจากปริมาณงานที่ทำ ไม่ได้มาจากสัดส่วนของช่องว่างที่ถูกใช้ไป
  let stressRaw = 0;
  for (const load of Object.values(out.dayLoad || {})) {
    if (load <= 0) continue;
    stressRaw += Math.pow(load / SUSTAINABLE_MIN, STRESS_EXP);
  }

  const stress = LAMBDA_STRESS * stressRaw;
  const sleep = LAMBDA_SLEEP * (out.pastBed || 0);

  return { total: grade + debt + stress + sleep, grade, debt, stress, sleep, perTask };
}

// ---------- สรุปหลายเส้นเป็นตัวเลขชุดเดียว ----------
// คืนทั้งค่าเฉลี่ยและส่วนเบี่ยงเบน เพราะการตัดสินใจใช้ทั้งสองตัว:
// เด็กที่มีสอบ 30% รับ "หางความเสี่ยง" ไม่ไหว สองทางที่ค่าเฉลี่ยเท่ากัน
// ต้องเลือกทางที่ผลลัพธ์แกว่งน้อยกว่าเสมอ (ดู KAPPA ใน decide.js)
function lossSummary(prep, losses) {
  const n = losses.length;
  if (!n) return null;
  const mean = k => losses.reduce((a, l) => a + l[k], 0) / n;
  const total = mean('total');
  const varSum = losses.reduce((a, l) => a + (l.total - total) * (l.total - total), 0) / n;

  // P(ทำไม่ทัน) รายใบ — นับจากจำนวนเส้นที่จบไม่ครบ ไม่ใช่จากสูตร
  // ตัวเลขนี้คือสิ่งที่เอาไปเขียนคำอธิบายข้อ 4 กับ 5 ("ปัญหาอะไรที่ถูกหลบ")
  const miss = new Array(prep.items.length).fill(0);
  for (const l of losses) for (const p of l.perTask) if (!p.done) miss[p.idx]++;

  return {
    total, sd: Math.sqrt(varSum),
    grade: mean('grade'), debt: mean('debt'), stress: mean('stress'), sleep: mean('sleep'),
    missP: miss.map(c => c / n),
    n,
  };
}
