test("records isolate mode and version, rank completed Hardcore first, and store summaries only",()=>{
  const data = new Map();
  const provider = new FrostRecords.LocalRecordProvider({setItem:(key,value)=>data.set(key,value),getItem:key=>data.get(key)});
  const row=(stage,wave,time,won=false,kind="hardcore")=>({kind,won,time,progress:{stage,wave,time:time-2},inventory:{secret:1}});
  [row(3,2,38),row(4,1,92),row(4,1,79),row(5,1,84,true),row(5,1,80,true),row(5,1,22,true,"story")].forEach(result=>provider.record(result));
  assert.deepEqual(provider.list({category:"progress"}).map(result=>result.time),[80,84,79,92,38]);
  assert.deepEqual(provider.list({category:"clear",mode:"story"}).map(result=>result.time),[22]);
  assert.equal(provider.canSubmitVerified,false);
  assert.ok(provider.list({category:"progress",source:"demo"}).every(result=>result.demo));
  assert.ok([...data.values()].every(value=>!value.includes("secret")&&!value.includes("inventory")));
  const stored = new FrostRecords.LocalRecordProvider({getItem:key=>data.get(key)});
  assert.equal(stored.list({category:"clear",mode:"hardcore"}).length,2);
  stored.records.push({...stored.records.find(record=>record.kind==="hardcore"),version:"2.0",time:555});
  stored.records.push({...stored.records.find(record=>record.kind==="hardcore"),version:"3.0",time:444});
  stored.record(row(4,1,45));
  assert.equal(stored.list({category:"progress",version:"2.0"})[0].time,555);
  assert.equal(stored.list({category:"progress",version:"3.0"})[0].time,444);
  assert.ok(stored.list({category:"progress"}).every(result=>result.version==="4.0"));
});

test("each seeded room keeps its route, central gate and spawn approach usable",()=>{
  for(const kind of ["story","hardcore","boss"]) for(let seed=0;seed<40;seed++) {
    const rooms=FrostWorld.route(kind,seed);
    assert.equal(rooms.at(-1).enemies[0],"king");
    for(const room of rooms) {
      assert.ok(room.pillars.every(([x,y,r])=>Math.hypot(x-GATE.x,y-GATE.y)>r+40));
      assert.ok(room.pillars.every(([x,y,r])=>Math.abs(480-x)>r+20));
    }
  }
  assert.ok(STEP>0);
});

