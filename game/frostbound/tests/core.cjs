test("all consumables change combat, and interrupted drinks remain in the pack",()=>{
  const run=new Run("training",15);
  run.enemies=[];
  run.gateOpen=true;
  const p=run.player;
  const drink = id=>{
    run.inventory.potions=[id];
    p.action=null;
    assert.ok(run.inventory.selectPotion(id));
    run.request("potion",input);
    tick(run,58);
  };
  drink("draught");
  assert.ok(run.buffs.draught>10);
  p.action=null;
  run.receiveHit({...syntheticAttack,frost:true},source,p);
  assert.equal(p.hp,81); assert.equal(p.frost,24);
  assert.equal(run.buffs.chill,undefined);
  drink("focus");
  assert.equal(run.regen,36);
  drink("iron");
  assert.equal(run.speed,1.06*.85);
  drink("ember");
  assert.ok(run.warmth);
  p.grace=0;
  const hp=p.hp;
  run.receiveHit({...syntheticAttack,frost:true},source,p);
  assert.equal(p.hp,hp-15);
  run.inventory.potions=["flask"];
  p.action=null;
  assert.ok(run.inventory.selectPotion("flask"));
  run.request("potion",input);
  tick(run,10);
  p.grace=0;
  run.receiveHit(syntheticAttack,source,p);
  tick(run,110);
  assert.deepEqual(run.inventory.potions,["flask"]);
});

test("safe rooms, hidden chest, stage transitions, and run reset",()=>{
  const run=new Run("story",29);
  run.pending=[];
  tick(run,1);
  assert.equal(run.mode,"choose");
  run.select(run.choices.at(-1).id,true);
  assert.equal(run.wave,1);
  Object.assign(run.player,GATE);
  tick(run,1);
  assert.equal(run.room.type,"merchant");
  Object.assign(run.player,NPC);
  assert.equal(run.target,"merchant");
  const stock=run.stock;
  assert.strictEqual(stock,run.stock);
  while(run.room.name!=="Hollowpine Forest") {
    if(!run.gateOpen) {
      run.pending=[];tick(run,1);run.select(run.choices.at(-1).id,true);
    }
    Object.assign(run.player,GATE);
    tick(run,1);
    if(run.paths) run.choosePath("safe");
  }
  run.pending=[];
  tick(run,1);
  run.select(run.choices.at(-1).id,true);
  Object.assign(run.player,SIDE);
  assert.equal(run.target,"passage");
  run.enterSide();
  assert.equal(run.room.type,"treasure");
  Object.assign(run.player,DISCOVERY);
  const before=run.inventory.crowns;
  if(run.room.hidden) run.eventRandom=()=>.25;
  run.discover("treasure");
  assert.ok(run.inventory.crowns>=before+15);
  const after=run.inventory.crowns;
  run.discover("treasure");
  assert.equal(run.inventory.crowns,after);
  if(run.choices.length) run.select(run.choices[0].id,true);
  Object.assign(run.player,GATE);
  tick(run,1);
  if(run.paths) run.choosePath("safe");
  assert.equal(run.room.stage,2);
  assert.notEqual(run.room.type,"secret");
  assert.ok(run.abandon());
  assert.equal(run.result.won,false);
  assert.equal(run.abandon(),false);
  const fresh=new Run("story",29);
  assert.equal(fresh.progress.stage,1);
  assert.equal(fresh.inventory.crowns,34);
  assert.deepEqual(fresh.inventory.potions,["flask"]);
});

