test("fixed-step swings, stamina, dash and perfect parry match their windows", () => {
  const run=new Run("training",4);
  const p=run.player;
  run.request("light",input);
  tick(run,10);
  assert.equal(p.action.swung,false);
  tick(run,5);
  assert.equal(p.action.swung,true);
  tick(run,50);
  run.request("dash",input);
  assert.equal(p.stamina,75);
  assert.equal(run.request("dash",input),false);
  tick(run,13);
  run.receiveHit(syntheticAttack,source,p);
  assert.equal(p.hp,100);
  tick(run,45);
  assert.ok(p.stamina>75);
  run.request("parry",input);
  tick(run,14);
  run.receiveHit(syntheticAttack,source,p);
  assert.equal(run.stats.parries,1);
  assert.equal(p.hp,100);
  tick(run,55);
  run.request("parry",input);
  tick(run,20);
  run.receiveHit(syntheticAttack,source,p);
  assert.equal(p.hp,81);
});

