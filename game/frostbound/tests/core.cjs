test("active encounter, pause, boss and unresolved attacks lock mutations at the inventory boundary",()=>{
  const run=new Run("story",29), bag=run.inventory;
  bag.obtain("fang");
  bag.obtain("frostguard");
  bag.obtain("azure");
  assert.equal(run.encounterState,"PREPARATION");
  assert.ok(run.equip("fang"));
  const delayedEquip=()=>bag.equip("frostguard");
  run.prepareEncounter();
  assert.equal(run.encounterState,"COMBAT");
  assert.equal(delayedEquip(),false);
  assert.equal(run.equip("edge"),false);
  assert.equal(bag.selectPotion("azure"),false);
  assert.equal(bag.sell("frostguard"),false);
  assert.equal(bag.gear.armor,"coat");
  run.player.hp=50;
  assert.ok(run.request("potion",input));
  tick(run,60);
  assert.equal(run.player.hp,90);
  assert.equal(bag.potion,null);
  assert.equal(bag.quickSlot,"flask");
  assert.deepEqual(bag.potions,["azure"]);
  assert.equal(bag.selectPotion("azure"),false);
  run.pending=[];
  run.enemies=[];
  run.gateOpen=true;
  run.shots.push({x:200,y:310});
  assert.equal(delayedEquip(),false);
  run.shots=[];
  assert.equal(delayedEquip(),false,"action is still active");
  tick(run,40);
  assert.ok(delayedEquip());
  assert.ok(bag.selectPotion("azure"));
  Object.assign(run.player,GATE);
  tick(run,1);
  assert.equal(run.encounterState,"SAFE");
  Object.assign(run.player,NPC);
  assert.equal(run.canTrade,true);
  assert.ok(run.equip("edge"));
  run.abandon();
  run.releaseResources();
  assert.equal(delayedEquip(),false);
  const rush=new Run("boss",12);
  rush.inventory.obtain("fang");
  rush.select(rush.choices[0].id); rush.prepareEncounter();
  assert.equal(rush.encounterState,"BOSS_COMBAT");
  assert.equal(rush.inventory.equip("fang"),false);
  const hard=new Run("hardcore",22);
  hard.inventory.obtain("fang");
  hard.pending=[];
  tick(hard,1);
  assert.equal(hard.encounterState,"TRANSITION");
  assert.equal(hard.inventory.equip("fang"),false);
});

test("comparison distinguishes larger damage from larger stamina cost and recovery",()=>{
  const compared=FrostItems.comparison(ITEMS.great,ITEMS.edge);
  const byName=name=>compared.find(row=>row.name===name);
  assert.equal(byName("Heavy damage").impact,1);
  assert.equal(byName("Heavy stamina").delta,10);
  assert.equal(byName("Heavy stamina").impact,-1);
  assert.equal(byName("Heavy recovery").impact,-1);
  assert.equal(byName("Attack speed").impact,-1);
  assert.equal(FrostItems.comparison(ITEMS.plate,ITEMS.coat).find(row=>row.name==="Defense").impact,1);
});
