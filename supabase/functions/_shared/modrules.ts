export function readVerdict(raw: string): Verdict | null {
  try {
    const m = raw.match(/\{[\s\S]*\}/);
    if (!m) return null;
    const v = JSON.parse(m[0]) as Verdict;
    return v && typeof v.verdict === 'string' ? v : null;
  } catch { return null; }
}

