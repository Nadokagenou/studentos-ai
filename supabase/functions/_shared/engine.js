// ---------- 0) เตรียมข้อความจากเสียงพูด ----------
// เสียงพูดมักได้เลขเป็นคำอ่าน ("ข้อหนึ่งถึงสิบ") ตัวแกะข้อความอ่านไม่ออก
// แปลงเฉพาะตำแหน่งที่มีคำนำหน้าชัดเจน เพื่อไม่ให้ไปโดนคำปกติ (เช่น "สี่แยก")
const THAI_DIGIT = { 'ศูนย์': 0, 'หนึ่ง': 1, 'สอง': 2, 'สาม': 3, 'สี่': 4, 'ห้า': 5, 'หก': 6, 'เจ็ด': 7, 'แปด': 8, 'เก้า': 9 };
const THAI_D_PAT = Object.keys(THAI_DIGIT).join('|');
const THAI_NUM_PAT = `(?:(?:ยี่|${THAI_D_PAT})?สิบ(?:เอ็ด|${THAI_D_PAT})?|${THAI_D_PAT})`;

function thaiWordToNumber(w) {
  if (!w.includes('สิบ')) return THAI_DIGIT[w];
  const [tensPart, onesPart] = w.split('สิบ');
  let v = tensPart ? (tensPart === 'ยี่' ? 2 : THAI_DIGIT[tensPart]) * 10 : 10;
  if (onesPart) v += onesPart === 'เอ็ด' ? 1 : (THAI_DIGIT[onesPart] || 0);
  return v;
}

function normalizeSpokenText(text) {
  let t = String(text || '');
  // คำนำหน้า + เลขคำอ่าน  เช่น "ข้อหนึ่ง" "บทที่สี่" "ถึงสิบ" "วันที่ยี่สิบห้า"
  const lead = '(ข้อที่|ข้อ|บทที่|บท|หน้าที่|หน้า|ชุดที่|ถึง|วันที่|ที่)';
  t = t.replace(new RegExp(lead + '\\s*' + THAI_NUM_PAT, 'g'), (m, pre) => {
    const num = thaiWordToNumber(m.slice(pre.length).trim());
    return num == null || isNaN(num) ? m : pre + ' ' + num + ' ';
  });
  // เลขคำอ่าน + หน่วยต่อท้าย  เช่น "ยี่สิบเปอร์เซ็นต์" "สี่สิบนาที" "สองชั่วโมง"
  const unit = '(เปอร์เซ็นต์|%|นาที|ชั่วโมง|ชม\\.?|โมง|ทุ่ม|คะแนน|วัน)';
  t = t.replace(new RegExp(THAI_NUM_PAT + '\\s*' + unit, 'g'), (m, u) => {
    const num = thaiWordToNumber(m.slice(0, m.length - u.length).trim());
    return num == null || isNaN(num) ? m : ' ' + num + ' ' + u;
  });
  return t.replace(/\s+/g, ' ').trim();
}

// ---------- 0.5) เตรียมข้อความจาก OCR ----------
// โมเดลภาษาไทยของ Tesseract คืนค่ามาแบบเว้นวรรคทีละตัวอักษร ("ก า ร บ ้ า น เค ม ี")
// ถ้าส่งเข้าตัวแกะข้อความตรง ๆ จะหาคำว่า "เคมี" หรือ "พรุ่งนี้" ไม่เจอเลย —
// ยุบช่องว่างที่คั่นกลางอักษรไทยก่อน (ไทยไม่เว้นวรรคในคำ จึงยุบได้ไม่เสียความหมาย)
function normalizeOcrText(text) {
  return String(text || '')
    .replace(/[|¦]/g, ' ')                       // เส้นตารางในใบงานที่ OCR อ่านเป็นขีด
    .replace(/([฀-๿])[ \t]+(?=[฀-๿])/g, '$1')    // ยุบช่องว่างที่คั่นกลางอักษรไทย
    .replace(/ํา/g, 'ำ')          // ยุบแล้วค่อยแก้ "ํ+า" ให้เป็น "ำ" ตัวเดียว
    .replace(/[ \t]{2,}/g, ' ')
    .trim();
}

// ---------- 0.6) จับคำแบบทนตัวอักษรเพี้ยน (ใช้กับข้อความจากรูปเท่านั้น) ----------
// OCR พลาดตัวเดียว includes() ก็หาไม่เจอทั้งคำ — ของจริงที่วัดมา "ฟิสิกส์" ถูกอ่านเป็น "แฟสักส"
// วิธีเทียบ: ตัดสระบน-ล่างกับวรรณยุกต์ทิ้ง → ยุบตัวอักษรที่หน้าตาใกล้กันให้เป็นตัวแทนเดียว
//   → วัดระยะแก้ไข (Levenshtein) กับทุกช่วงของข้อความที่ยาวใกล้เคียงกัน
// เปิดเฉพาะข้อความจากรูป — ที่พิมพ์เองหรือแปะจาก LINE ถือว่าถูกอยู่แล้ว ไม่ต้องเดาให้เสี่ยง
const OCR_LOOKALIKE = [
  'ผฝพฟ', 'กถภฦ', 'ขชซฃ', 'บปษ', 'ดคตฅ', 'นมณ', 'รว', 'ลส',
  'อฮธ', 'จฉฐ', 'เแ', 'ไใโ', 'หฬ', '0Oo', '1lI|ๅ', '5S', '8B',
];
const LOOKALIKE_MAP = (() => {
  const m = {};
  for (const cls of OCR_LOOKALIKE) for (const ch of cls) m[ch] = cls[0];
  return m;
})();

// คีย์สำหรับเทียบ: ตัดเครื่องหมายบน-ล่าง แล้วยุบตัวที่หน้าตาคล้ายกัน
// keepGap = คงรอยต่อระหว่างคำไว้เป็นตัวคั่น (ใช้กับข้อความที่ถูกค้นหา)
const OCR_GAP = '';
function ocrKey(s, keepGap) {
  let out = '';
  for (const ch of String(s).toLowerCase().replace(/[ัิ-ฺ็-๎]/g, '')) {
    if (ch === ' ') { if (keepGap) out += OCR_GAP; continue; }
    out += LOOKALIKE_MAP[ch] || ch;
  }
  return out;
}

// Levenshtein ที่เลิกคิดทันทีเมื่อเกินเพดาน — ไม่ต้องคำนวณจนจบให้เปลือง
function editDistance(a, b, cap) {
  const n = a.length, m = b.length;
  if (Math.abs(n - m) > cap) return cap + 1;
  let prev = Array.from({ length: m + 1 }, (_, j) => j);
  for (let i = 1; i <= n; i++) {
    const cur = [i];
    let best = i;
    for (let j = 1; j <= m; j++) {
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
      if (cur[j] < best) best = cur[j];
    }
    if (best > cap) return cap + 1;
    prev = cur;
  }
  return prev[m];
}

// ระยะที่ดีที่สุดของคำนี้ในข้อความ (null = ไม่เจอในเพดานที่ยอมได้)
// คำที่สั้นกว่า 4 ตัวหลังยุบ ไม่เอามาเดา — สั้นเกินจนชนคำอื่นได้ง่าย
function fuzzyDistance(hay, needle) {
  const h = ocrKey(hay, true), k = ocrKey(needle);
  if (k.length < 4 || !h) return null;
  if (h.includes(k)) return 0;
  // คำสั้นต้องตรงเป๊ะหลังยุบตัวอักษร ยอมให้เพี้ยนได้เฉพาะคำที่ยาวพอ
  // ("สังคม" ยุบแล้วเหลือ 4 ตัว ถ้ายอมให้พลาด 1 ตัว คำว่า "ส่งวันศุกร์" จะกลายเป็นวิชาสังคมทันที)
  const cap = k.length >= 8 ? 2 : k.length >= 6 ? 1 : 0;
  if (!cap) return null;
  let best = cap + 1;
  for (let len = Math.max(1, k.length - cap); len <= k.length + cap; len++) {
    for (let i = 0; i + len <= h.length; i++) {
      const win = h.substr(i, len);
      // ชื่อวิชาเป็นคำเดียว ห้ามให้ช่วงที่จับได้คร่อมรอยต่อระหว่างคำ
      // (ไม่งั้น "เคม ครมาล" จะกลายเป็น "ดนตรี" เพราะตัวอักษรบังเอิญเรียงพอดี)
      if (win.includes(OCR_GAP)) continue;
      const d = editDistance(win, k, cap);
      if (d < best) best = d;
      if (best === 0) return 0;
    }
  }
  return best <= cap ? best : null;
}

// ---------- 0.7) นาฬิกาแบบที่คนไทยพูดจริง ----------
// ของเดิมรู้จักเวลาสองแบบ: "16:00" กับ "เที่ยง" — นอกนั้นเงียบ ๆ ตกไปที่ 23:59
// แปลว่างานที่ครูบอกว่า "ส่งบ่าย 3" ถูกแอปเชื่อว่ายังมีเวลาเหลืออีกเก้าชั่วโมงที่ไม่มีอยู่จริง
// และไม่มีสัญญาณอะไรบอกว่าอ่านไม่ออก — ผิดแบบเงียบคือแบบที่แพงที่สุด
//
// ลำดับในตารางนี้ห้ามสลับ: คำที่ยาวกว่าต้องมาก่อนคำที่เป็นส่วนหนึ่งของมัน
// "เที่ยงคืน" ต้องถูกจับก่อน "เที่ยง" ไม่งั้นเส้นตายเที่ยงคืน (ค่าเริ่มต้นของ Google Classroom
// และเป็นเส้นตายที่พบบ่อยที่สุดของงานออนไลน์) จะกลายเป็นเที่ยงวัน = เลยกำหนดไปแล้วครึ่งวัน
const CLOCK_WORD_NUM = { 'นึง': 1, 'หนึ่ง': 1, 'สอง': 2, 'สาม': 3, 'สี่': 4, 'ห้า': 5, 'หก': 6, 'เจ็ด': 7, 'แปด': 8, 'เก้า': 9, 'สิบ': 10, 'สิบเอ็ด': 11 };
// ประกอบจาก .source ของ regex จริง ไม่ใช่สตริงที่พิมพ์ escape เอง —
// สตริงที่มี backslash ตัวเดียวใน JS จะถูกกลืนตั้งแต่ตอนอ่านสตริง ('\d' คือ 'd' เฉย ๆ)
// แล้วกลายเป็น regex ที่ไล่หาตัวอักษร d ในประโยคภาษาไทย ซึ่งไม่เคยเจอ และไม่มีอะไรฟ้อง
const CLOCK_N = '(' + /\d{1,2}/.source + '|' + Object.keys(CLOCK_WORD_NUM).join('|') + ')';
const SP = '[ ]?';   // ช่องว่างที่จะมีหรือไม่มีก็ได้ · เขียนเป็นคลาสเพื่อเลี่ยง backslash ในสตริง
function clockNum(w) {
  if (w == null) return null;
  const n = CLOCK_WORD_NUM[w];
  return n != null ? n : (/^\d+$/.test(w) ? +w : null);
}

// คืน { hh, mm, text } หรือ null · text คือคำที่ใช้ตัดสิน ไว้หักออกจากรายละเอียดทีหลัง
function readThaiClock(t) {
  let m;
  // เที่ยงคืน — นโยบาย: 23:59 ของวันเดียวกัน ไม่ใช่ 00:00 ของวันถัดไป
  // เพราะคนพูดว่า "ส่งเที่ยงคืนวันนี้" หมายถึงปลายสุดของวันนี้ ไม่ใช่ต้นวันพรุ่งนี้
  if ((m = t.match(/เที่ยงคืน/)))            return { hh: 23, mm: 59, text: m[0] };
  if ((m = t.match(/(\d{1,2})[:.](\d{2})\s*(?:น\.?)?/)) && +m[1] <= 23 && +m[2] <= 59)
    return { hh: +m[1], mm: +m[2], text: m[0] };
  // ตี 5 = 05:00 · ต้องมีตัวเลขติดกันเสมอ ไม่งั้น "ตีความ" กลายเป็นเวลา
  if ((m = t.match(new RegExp('ตี' + SP + CLOCK_N))) && clockNum(m[1]) >= 1 && clockNum(m[1]) <= 5)
    return { hh: clockNum(m[1]), mm: 0, text: m[0] };
  // ทุ่ม = หลังหนึ่งทุ่ม (19:00) ไปอีก n−1 ชม. · "ทุ่มนึง" กับ "สองทุ่ม" เลขอยู่คนละข้างของคำ
  if ((m = t.match(new RegExp('ทุ่ม' + SP + '(นึง|หนึ่ง|ครึ่ง)?|' + CLOCK_N + SP + 'ทุ่ม(?:ครึ่ง)?')))) {
    const n = clockNum(m[2]) != null ? clockNum(m[2]) : 1;
    if (n >= 1 && n <= 6) return { hh: 18 + n, mm: /ครึ่ง/.test(m[0]) ? 30 : 0, text: m[0] };
  }
  // บ่าย 3 = 15:00 · "บ่ายโมง" = 13:00 (ไม่มีเลขให้จับ)
  if ((m = t.match(new RegExp('บ่าย' + SP + '(?:' + CLOCK_N + SP + ')?(?:โมง)?')))) {
    const n = clockNum(m[1]) != null ? clockNum(m[1]) : 1;
    if (n >= 1 && n <= 5) return { hh: 12 + n, mm: 0, text: m[0] };
  }
  // n โมงเย็น = 12+n · n โมงเช้า = n · "โมง" เปล่า ๆ ตีเป็นเช้าเมื่อเลขยังเป็นเวลาเช้าได้
  if ((m = t.match(new RegExp(CLOCK_N + SP + 'โมง' + SP + '(เย็น|เช้า)?')))) {
    const n = clockNum(m[1]);
    if (n != null) {
      if (m[2] === 'เย็น' && n >= 1 && n <= 6) return { hh: 12 + n, mm: 0, text: m[0] };
      if (n >= 1 && n <= 11)                   return { hh: n, mm: 0, text: m[0] };
    }
  }
  if ((m = t.match(/เที่ยง(?:วัน)?/)))       return { hh: 12, mm: 0, text: m[0] };
  if ((m = t.match(new RegExp(CLOCK_N + SP + 'นาฬิกา')))) {
    const n = clockNum(m[1]);
    if (n != null && n <= 23) return { hh: n, mm: 0, text: m[0] };
  }
  return null;
}

// ---------- 1) แกะข้อความ ----------
// opts.fuzzy = ข้อความมาจาก OCR ให้ยอมให้ตัวอักษรเพี้ยนได้
function parseAssignment(text, now = new Date(), opts = {}) {
  const fuzzy = !!opts.fuzzy;
  const t = String(text || '').replace(/\s+/g, ' ').trim();
  const detected = {};

  // วิชา
  // ตัด "กับดัก" ออกก่อนค้นหา — คำที่มีคำค้นของวิชาฝังอยู่แต่ไม่ได้หมายถึงวิชานั้น
  // "เลขที่ 5" คือลำดับนักเรียน ไม่ใช่วิชาคณิตศาสตร์ (คำค้น 'เลข' ไปจับเข้าเต็ม ๆ)
  // ตัดออกทั้งข้อความก่อนค้น จึงกันได้ทุกตำแหน่ง ไม่ใช่แค่ตำแหน่งแรกที่เจอ
  const SUBJECT_TRAPS = /เลขที่/g;
  let subject = 'อื่น ๆ', subjKey = '';
  const tSubj = t.replace(SUBJECT_TRAPS, ' ');
  const low = tSubj.toLowerCase();
  outer:
  for (const s of SUBJECTS) {
    for (const k of s.keys) {
      if (low.includes(k.toLowerCase())) {
        subject = s.name; subjKey = k; detected.subject = true; break outer;
      }
    }
  }
  // หาแบบตรงตัวไม่เจอ + ข้อความมาจากรูป → เดาแบบทนเพี้ยน
  // เลือกวิชาที่ "ใกล้ที่สุด" ทั้งกระดาน ไม่ใช่ตัวแรกที่ผ่านเกณฑ์ — กันคำสั้นแย่งไปก่อน
  if (subject === 'อื่น ๆ' && fuzzy) {
    let best = null;
    for (const s of SUBJECTS) {
      for (const k of s.keys) {
        const d = fuzzyDistance(tSubj, k);
        if (d == null) continue;
        if (!best || d < best.d) best = { d, name: s.name };
      }
    }
    if (best) { subject = best.name; detected.subject = true; detected.subjectFuzzy = true; }
  }

  // ครู (เอาเฉพาะชื่อ — หยุดที่ช่องว่างหรือคำที่ขึ้นความใหม่ ไม่ลากประโยคทั้งท่อนมา
  // สำคัญกับข้อความจาก OCR ที่ไม่มีช่องว่างคั่นคำเลย เช่น "ครูมาลีทำแบบฝึกหัด")
  let teacher = '';
  // คำที่แปลว่า "จบชื่อครูแล้ว" — ไม่งั้นชื่อจะลากประโยคถัดไปมาด้วย
  // เช่น "ครูมาลีสั่งงานเคมี" ต้องได้ "ครูมาลี" ไม่ใช่ทั้งท่อน
  // รวมชั้นเรียนไว้ด้วย (ม.5/2 · ป.6 · ห้อง · ชั้น) — ใบงานมักพิมพ์ชื่อครูติดชั้นเรียนเลย
  // และภาษาไทยไม่การันตีว่าจะมีช่องว่างคั่น ถ้ารอแต่ช่องว่างจะจับชื่อครูไม่ได้ทั้งท่อน
  // (วัดจริงเจอ "ครูสมชายม.5/2" แล้วหลุดทั้งช่อง ทั้งที่ OCR อ่านถูกทุกตัว)
  const nameEnd = 'สั่ง|ให้|บอก|แจ้ง|มอบหมาย|นัด|ฝาก|ทำ|อ่าน|เขียน|สรุป|ท่อง|เตรียม|วาด|ส่ง|สอบ|แบบฝึกหัด|แบบ|บทที่|บท|ข้อ|หน้า|ใบงาน|คะแนน|ภายใน|เวลา|วันที่|วันนี้|พรุ่งนี้|มะรืน|สัปดาห์'
    + '|ม\\.\\s?\\d|ป\\.\\s?\\d|มัธยม|ประถม|ชั้น|ห้อง';
  // คำที่ตามหลัง "ครู" แล้วแปลว่า **ไม่มีชื่อครูอยู่ตรงนี้** — ต้องกันตั้งแต่ก่อนเริ่มจับ
  // "ส่งครูวันศุกร์" แปลว่าส่งให้ครูภายในวันศุกร์ ไม่ใช่ครูที่ชื่อ "วันศุกร์"
  // กันด้วย nameEnd ไม่ได้ เพราะ nameEnd เป็นตัวบอกว่า "ชื่อจบตรงไหน" —
  // ต่อให้ใส่ชื่อวันลงไป มันก็จะได้ "ครูวัน" มาแทน ซึ่งยังผิดอยู่ดี
  // คำกริยาที่ตามหลัง "ครู" ได้ทันที ต้องอยู่ในนี้ด้วย ไม่ใช่อยู่แต่ใน nameEnd —
  // nameEnd เป็นตัวบอกว่า "ชื่อจบตรงไหน" ซึ่งถูกเช็คหลังกินตัวอักษรไปแล้วอย่างน้อยสองตัว
  // "ครูสั่งงานเคมี" จึงกินคำว่า "สั่" ไปก่อนแล้วไล่หาที่จบต่อ ได้ชื่อครูว่า "ครูสั่งงานเคมี" ทั้งท่อน
  // ซึ่งเป็นสำนวนที่พบบ่อยที่สุดสำนวนหนึ่งในกลุ่ม LINE ของห้อง
  const notName = 'วัน|พรุ่ง|มะรืน|สัปดาห์|ที่|ใหญ่|ประจำ|ผู้|ทุก|และ|กับ'
    + '|สั่ง|ให้|บอก|แจ้ง|มอบหมาย|นัด|ฝาก|ส่ง|ทำ|เตือน|ยัง|ก็|จะ|ได้';
  const mT = t.match(new RegExp(
    '(?:ครู|อาจารย์|อ\\.)\\s?(?!' + notName + ')([ก-๙A-Za-z]{2,20}?)(?=\\s|' + nameEnd + '|$)'));
  // ด่านสุดท้าย: ชื่อที่มีคำว่างาน/การบ้านฝังอยู่ ไม่ใช่ชื่อคน มันคือประโยคที่หลุดมา
  if (mT && !/สั่ง|การบ้าน|ใบงาน|^งาน|งาน$/.test(mT[1])) {
    teacher = 'ครู' + mT[1].replace(/^ครู/, ''); detected.teacher = true;
  }

  // คะแนน
  // รับทั้ง "20%" · "รวม 20 คะแนน" · "คะแนนเก็บ 20" · และ "10 คะแนน" (เลขมาก่อนคำ)
  //
  // ลำดับสำคัญ: ข้อความจริงมักบอกทั้งคะแนนต่อข้อและคะแนนรวมในประโยคเดียว
  // "ทำ 10 ข้อ ข้อละ 2 คะแนน รวม 20 คะแนน" — เลขที่ผู้ใช้หมายถึงคือ 20 ไม่ใช่ 2
  // ของเดิมหยิบตัวแรกที่เจอจึงได้ 2 มาตลอด
  let scorePct = null, scoreText = '';
  const mPct = t.match(/(\d{1,3})\s*(?:%|เปอร์เซ็นต์)/);
  const mTotal = t.match(/(?:รวม|ทั้งหมด|เต็ม)\s*(\d{1,3})\s*คะแนน/);
  const mKeep = t.match(/คะแนน(?:เก็บ)?\s*(\d{1,3})/);
  if (mPct) { scorePct = +mPct[1]; scoreText = mPct[0]; }
  else if (mTotal) { scorePct = +mTotal[1]; scoreText = mTotal[0]; }
  else if (mKeep) { scorePct = +mKeep[1]; scoreText = mKeep[0]; }
  else {
    // ไม่มีคำบอกว่าอันไหนคือคะแนนรวม → เอาเลขที่มากที่สุด
    // คะแนนรวมมากกว่าคะแนนต่อข้อเสมอ จึงเป็นการเดาที่ปลอดภัยกว่าหยิบตัวแรก
    const all = [...t.matchAll(/(\d{1,3})\s*คะแนน/g)];
    if (all.length) {
      const best = all.reduce((a, b) => (+b[1] > +a[1] ? b : a));
      scorePct = +best[1]; scoreText = best[0];
    }
  }
  if (scorePct != null) { scorePct = Math.min(100, scorePct); detected.score = true; }

  // เวลา — ดู readThaiClock() ข้างบน · ไม่เจอเวลาเลยถึงจะตกมาที่ปลายวัน
  let hh = 23, mm = 59, hasTime = false, timeText = '';
  const clock = readThaiClock(t);
  if (clock) { hh = clock.hh; mm = clock.mm; hasTime = true; timeText = clock.text; }

  // วันส่ง — dueText เก็บคำที่ใช้ตัดสิน ไว้เอาไปหักออกจากรายละเอียดทีหลัง
  let due = null, dueText = '';
  if (/วันนี้/.test(t)) { due = atTime(now, hh, mm); dueText = 'วันนี้'; }
  else if (/พรุ่งนี้/.test(t)) { due = atTime(addDays(now, 1), hh, mm); dueText = 'พรุ่งนี้'; }
  else if (/มะรืน/.test(t)) { due = atTime(addDays(now, 2), hh, mm); dueText = 'มะรืน'; }
  else {
    // "วันศุกร์" / "ศุกร์หน้า"
    for (const [name, dow] of Object.entries(WEEKDAYS)) {
      // กลืน "นี้" ท้ายคำไปด้วย — "ภายในวันศุกร์นี้" ที่จับแค่ "วันศุกร์"
      // จะทิ้งคำว่า "นี้" ค้างอยู่ในรายละเอียด กลายเป็น "ส่งใบงานภาษาไทยภายใน นี้"
      const re = new RegExp('(?:วัน)?' + name + '(หน้า|นี้)?');
      const m = t.match(re);
      if (m) {
        let diff = (dow - now.getDay() + 7) % 7;
        if (diff === 0) diff = 7;              // "วันศุกร์" ในวันศุกร์ = ศุกร์ถัดไป
        if (m[1] === 'หน้า') diff += 7;
        due = atTime(addDays(now, diff), hh, mm);
        dueText = m[0];
        break;
      }
    }
  }
  if (!due) {
    // "25 ก.ค." / "วันที่ 25 กรกฎาคม"
    for (const [mon, idx] of Object.entries(THAI_MONTHS)) {
      const re = new RegExp('(?:วันที่\\s*)?(\\d{1,2})\\s*' + mon.replace('.', '\\.'));
      const m = t.match(re);
      if (m) {
        let d = new Date(now.getFullYear(), idx, +m[1], hh, mm);
        if (d < now) d = new Date(now.getFullYear() + 1, idx, +m[1], hh, mm);
        due = d;
        dueText = m[0];
        break;
      }
    }
  }
  if (!due) {
    const mIn = t.match(/ภายใน\s*(\d{1,2})\s*วัน/);
    if (mIn) { due = atTime(addDays(now, +mIn[1]), hh, mm); dueText = mIn[0]; }
    else if (/สัปดาห์หน้า/.test(t)) { due = atTime(addDays(now, 7), hh, mm); dueText = 'สัปดาห์หน้า'; }
  }
  // ทางสำรองสำหรับข้อความจากรูป: OCR มักทำวรรณยุกต์/สระหาย ("พรุ่งน่" แทน "พรุ่งนี้")
  // จับแบบตัดวรรณยุกต์กับสระบน-ล่างทิ้งทั้งสองฝ่าย — ใช้เฉพาะเมื่อจับตรงตัวไม่ได้
  // และเฉพาะคำบอกวันที่ยาวพอจะไม่ชนคำอื่น (ไม่รวมชื่อวันในสัปดาห์ที่สั้นเกินไป)
  if (!due) {
    // ตัดสระบน/ล่าง + วรรณยุกต์ (ไม่แตะ า ำ ที่เป็นสระเต็มตัว)
    const bare = s => s.replace(/[ัิ-ฺ็-๎]/g, '');
    const lt = bare(t);
    if (lt.includes(bare('วันนี้')))         due = atTime(now, hh, mm);
    else if (lt.includes(bare('พรุ่งนี้')))  due = atTime(addDays(now, 1), hh, mm);
    else if (lt.includes(bare('มะรืน')))     due = atTime(addDays(now, 2), hh, mm);
  }
  // บอกเวลามาแต่ไม่ได้บอกวัน = วันนี้ — และถ้าเวลานั้นผ่านไปแล้วก็คือพรุ่งนี้
  // ("ส่งเที่ยงคืนนี้" ไม่มีคำว่าวันนี้อยู่ในประโยคเลย แต่ไม่มีใครตีความเป็นอย่างอื่น)
  // ไม่มีบรรทัดนี้ ประโยคพวกนี้จะได้ due = null แล้วงานจะไปกองอยู่ท้ายลำดับความสำคัญ
  if (!due && hasTime) {
    const todayAt = atTime(now, hh, mm);
    due = todayAt > now ? todayAt : atTime(addDays(now, 1), hh, mm);
    dueText = '';
  }
  if (due) detected.due = true;

  // เวลาที่ใช้ทำ (นาที)
  let estMin = null;
  const mMin = t.match(/(\d{1,3})\s*นาที/);
  const mHr = t.match(/(\d{1,2}(?:\.\d)?)\s*(?:ชม\.?|ชั่วโมง)/);
  let mRange = t.match(/ข้อ\s*(\d{1,3})\s*[-–ถึง]+\s*(\d{1,3})/);
  // จากรูป คำว่า "ข้อ" มักเพี้ยนจนหาไม่เจอ (ของจริงที่วัดมา อ่านได้เป็น "Jo 1-10")
  // ยอมรับช่วงตัวเลขล้วนแทน แต่ต้องดูเหมือนช่วงข้อจริง ๆ: เรียงจากน้อยไปมาก ห่างกันไม่เกิน 100
  // และต้องไม่ติดกับ : . / - ซึ่งแปลว่าเป็นเวลา วันที่ หรือเลขชุดอื่น
  if (!mRange && fuzzy) {
    const m = t.match(/(?:^|[^\d:.\/-])(\d{1,3})\s*[-–—]\s*(\d{1,3})(?![\d:.\/-])/);
    if (m && +m[2] > +m[1] && +m[2] - +m[1] <= 100) mRange = m;
  }
  // "ส่งคณิต 20 ข้อ" บอกขนาดงานชัดพอ ๆ กับ "ข้อ 1-20" — ต่างกันแค่รูปประโยค
  // ไม่จับแบบนี้ งานยี่สิบข้อกับงานสองข้อจะได้เวลาเท่ากันที่ 30 นาที แล้วแผนทั้งวันเพี้ยนตาม
  const mCount = t.match(/(\d{1,3})\s*ข้อ/);
  if (mMin) estMin = +mMin[1];
  else if (mHr) estMin = Math.round(+mHr[1] * 60);
  else if (mRange) estMin = Math.max(10, (+mRange[2] - +mRange[1] + 1) * 4);
  else if (mCount) estMin = Math.max(10, Math.min(180, +mCount[1] * 4));
  if (estMin) detected.est = true;

  // ประเภท: เดาจากคำที่นักเรียนใช้จริง (ตรวจสอบก่อน เพราะกิจกรรมบางอย่างมีคำว่า "สอบ" ปนไม่ได้)
  let type = 'homework';
  if (/สอบ(?!ถาม)|quiz|test|มิดเทอม|ไฟนอล|กลางภาค|ปลายภาค/i.test(t)) type = 'exam';
  // "นัด" ต้องไม่ตามด้วย "ส่ง" — "ครูนัดส่งงานวันศุกร์" คือการบ้าน ไม่ใช่กิจกรรม
  // (กิจกรรมคือเหตุการณ์ที่ต้องไปอยู่ตรงนั้น ส่วนการนัดส่งงานยังเป็นงานที่ต้องนั่งทำ
  //  แยกผิดแล้วกระทบจริง: กิจกรรมไม่ถูกจัดเวลาให้ในแผนของวัน)
  else if (/กิจกรรม|ประชุม|ซ้อม|แข่ง|เข้าค่าย|ค่าย|ทัศนศึกษา|ตักบาตร|เข้าแถว|พิธี|งานวัด|ชมรม|บำเพ็ญ|จิตอาสา|อบรม|สัมมนา|ไปงาน|นัด(?!ส่ง|หมายส่ง)/i.test(t)) type = 'activity';
  // "อย่าลืม" ไม่ได้แปลว่าไม่ใช่งาน — มันคือคำที่ครูใช้ขึ้นต้นประโยคสั่งงานบ่อยที่สุด
  // ของเดิมให้ "อย่าลืม" ชนะคำว่า "ใบงาน" ผลคือการบ้านจริงกลายเป็น reminder
  // ซึ่ง schedulable:false = ไม่เคยถูกจัดเวลาให้ในแผนของวันเลยสักครั้ง งานหายทั้งใบแบบเงียบ ๆ
  // ส่ง(?!เงิน|ค่า|ตัว) กันไม่ให้ "อย่าลืมส่งเงินค่าเทอม" ถูกลากมาเป็นการบ้านด้วย
  else if (/เตือน|อย่าลืม|จำไว้|ติดต่อ|จ่ายเงิน|จ่ายค่า|ส่งเงิน/i.test(t)
    && !/การบ้าน|ใบงาน|แบบฝึกหัด|รายงาน|โจทย์|เรียงความ|ท่อง|สรุป|ทำ|เขียน|อ่าน|ส่ง(?!เงิน|ค่า|ตัว)/.test(t)) type = 'reminder';
  if (type !== 'homework') detected.type = true;
  const isExam = type === 'exam'; // เก็บไว้เพื่อความเข้ากันได้กับข้อมูลเก่า

  // ---------- รายละเอียด ----------
  // วิธีเดิมจับเฉพาะประโยคที่ขึ้นต้นด้วยคำกริยา แล้วตัดจบทันทีที่เจอคำบอกกำหนดส่ง
  // ข้อความยาว ๆ ที่แปะจาก LINE จึงหายไปครึ่งหนึ่ง (เจอ "ส่ง" กลางประโยคก็ตัดแล้ว)
  // วิธีใหม่: เอาข้อความทั้งก้อน แล้ว "หักเฉพาะส่วนที่ถูกแยกไปช่องอื่นแล้ว" ออก
  // ที่เหลือคือสิ่งที่ผู้ใช้เขียนจริง ๆ และไม่มีอะไรหายไประหว่างทาง
  const escRe = s => String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const cutOut = [dueText, mT && mT[0], scoreText, mMin && mMin[0], mHr && mHr[0]].filter(Boolean);
  if (timeText && !(dueText && dueText.includes(timeText))) cutOut.push(timeText);

  let rest = t;
  for (const piece of cutOut) rest = rest.replace(piece, ' ');
  // "ส่ง" ที่เกาะติดคำถัดไป ต้องตัดก่อนบรรทัดล่าง ไม่งั้นมันบัง ^ ไว้ทั้งชุด
  // ผลที่เห็นบนเครื่องจริง: การ์ดขึ้น "เคมี · ส่งใบงานเคมี บทที่ 4" — ชื่อวิชาซ้ำสองรอบ
  // (ชุดล้างข้างล่างที่มี "ส่ง" อยู่ด้วย รอช่องว่างนำหน้า จึงไม่เคยเข้าเงื่อนไขกับคำที่เกาะกัน)
  //
  // ตัดเฉพาะตอนที่ตามหลังเป็นคำเรียกงานที่รู้จักเท่านั้น — ตัด "ส่ง" ดื้อ ๆ ทุกที่
  // จะกิน "ส่งเสริมสุขภาพ" เหลือ "เสริมสุขภาพ" ซึ่งผิดแบบที่ไม่มีใครสังเกตจนสาย
  rest = rest.replace(/^\s*ส่ง(?=ใบงาน|การบ้าน|รายงาน|ชิ้นงาน|แบบฝึกหัด|โครงงาน|ผังงาน|ชีท|งาน)/, '');
  // คำเรียกงาน + ชื่อวิชาที่ต้นประโยค ซ้ำกับช่อง "วิชา" อยู่แล้ว
  if (subjKey) rest = rest.replace(new RegExp('^\\s*(?:การบ้าน|ใบงาน|วิชา|งาน)?\\s*' + escRe(subjKey), 'i'), ' ');
  // คำเชื่อมที่ค้างลอยอยู่หลังหักข้อมูลออก (เช่น "…ส่ง  16:00" เหลือ "ส่ง" โดด ๆ)
  // ภาษาไทยไม่เว้นวรรคระหว่างคำ คำเชื่อมจึงมักติดกับคำข้างหน้า ("…ภาษาไทยภายใน")
  // การรอให้มีช่องว่างนำหน้าจึงแทบไม่เคยเข้าเงื่อนไขเลย · คำในชุดนี้ยาวและเฉพาะพอ
  // ที่จะไม่ไปโผล่กลางคำอื่น จึงตัดได้โดยไม่ต้องรอช่องว่าง
  rest = rest
    .replace(/(?:ภายใน|กำหนดส่ง|เดดไลน์|คะแนนเก็บ|ใช้เวลา(?:ประมาณ)?|ประมาณ)/g, ' ')
    .replace(/(?:^|\s)(?:ส่ง|คะแนน|เก็บ|เวลา|ตอน|น\.|ครู|อาจารย์)(?=\s|$)/g, ' ')
    .replace(/\s{2,}/g, ' ')
    // คำที่ค้างอยู่ท้ายสุดหลังหักข้อมูลออก ("สอบวันพุธ" → เหลือ "สอบ" ลอย ๆ)
    .replace(/\s(?:สอบ|ส่ง|เริ่ม|ก่อน|ตอน|ภายใน|ที่|เมื่อ|วัน)\s*$/, '')
    // คำแบ่งส่วนที่ค้างท้ายหลังหักจำนวนออก — "กลุ่มละ 5 นาที" ถูกอ่านเป็นเวลาที่ใช้ทำ
    // (ถูกแล้ว) แต่ทิ้ง "กลุ่มละ" ค้างไว้ท้ายรายละเอียด
    // ไม่รอช่องว่างนำหน้าเหมือนชุดข้างบน เพราะคำพวกนี้เกาะติดคำก่อนหน้าเสมอ ("ใบงานคนละ")
    // ปลอดภัยเพราะไม่มีงานจริงงานไหนจบประโยคด้วย "…ละ" — เจอค้างท้าย = หักไม่หมดเสมอ
    .replace(/(?:กลุ่ม|คน|ข้อ|อัน|ชิ้น|หน้า|ครั้ง|วัน)ละ\s*$/, '')
    .replace(/^[\s·,:;\-–—]+|[\s·,:;\-–—(]+$/g, '')
    .trim();

  let detail = '';
  if (rest.length >= 3) { detail = rest.slice(0, 200); detected.detail = true; }
  else {
    // ข้อความสั้นมากจนหักแล้วไม่เหลืออะไร → ใช้ข้อความเดิมทั้งก้อน ดีกว่าปล่อยว่าง
    detail = t.slice(0, 200);
  }

  // สอบที่ไม่ได้บอกเวลา ตกลงกันว่าเป็น 08:00 ไม่ใช่ 23:59
  // สอบอยู่ต้นวัน การตั้งไว้ปลายวันคือการแจกเวลาอ่านหนังสือปลอมให้อีกสิบหกชั่วโมง
  // แล้วแผนก็จะบอกให้ไปอ่านตอนเย็นของวันที่สอบเสร็จไปแล้ว
  // ยกเว้นกรณีที่ 08:00 ของวันนั้นเลยไปแล้ว — ย้อนเวลาให้ผู้ใช้ไม่ได้ ปล่อยไว้ที่เดิมดีกว่า
  if (due && type === 'exam' && !hasTime) {
    const morning = atTime(due, 8, 0);
    if (morning > now) due = morning;
  }

  return {
    subject, teacher, scorePct,
    due: due ? due.toISOString() : null,
    // ค่าปริยายของ "สอบ" ต้องเป็นเวลาอ่านหนังสือ ไม่ใช่ 30 นาทีเท่าการบ้านใบหนึ่ง
    // สอบทั้งบทที่อ่านจบใน 30 นาทีไม่มีอยู่จริง และตัวเลขนี้ไม่ได้อยู่เฉย ๆ —
    // มันคือจำนวนนาทีที่ตัวจัดแผนจะกันไว้ให้ ตั้งต่ำไว้ = แผนบอกว่าอ่านครึ่งชั่วโมงแล้วพอ
    // (ผู้ใช้แก้ได้ในหน้ายืนยันเสมอ · planner.js แตกเป็นรอบอ่านย่อย ๆ ให้อีกที)
    estMin: estMin || (type === 'activity' || type === 'reminder' ? 15
      : type === 'exam' ? 120 : 30),
    type, isExam, detail, detected, raw: text,
  };
}

// ---------- 2) ลำดับความสำคัญ + เหตุผล ----------

// เวลาที่ยังต้องนั่งทำอีก — งานที่ทำไปครึ่งใบแล้วไม่ควรถูกกันเวลาไว้เต็ม
// ทั้งคะแนนความสำคัญและตัวจัดแผนต้องอ่านตัวเลขเดียวกัน ไม่งั้นแผนกับป้ายบนการ์ดจะไม่ตรงกัน
function remainingMin(t) {
  return Math.max(10, Math.round((t.estMin || 30) * (1 - (t.progress || 0) / 100)));
}

// ความด่วนเป็นเส้นโค้งต่อเนื่อง ไม่ใช่บันได
//
// ของเดิมเป็นบันได 6 ขั้น (+50 / +40 / +28 / +14 / +5) ซึ่งพังสองทาง:
// งานที่เหลือ 5.9 ชม. กับ 6.1 ชม. ห่างกัน 10 คะแนนทั้งที่ต่างกันสิบสองนาที
// และช่วง "ส่งใน 5 ชม." กับ "ส่งใน 30 ชม." ก็ห่างกันแค่ 10 คะแนน — น้อยกว่าโบนัสสอบ
// ผลคือสอบอีกสามวันแซงการบ้านที่ส่งคืนนี้ ซึ่งเป็นความผิดที่แพงที่สุดที่แอปนี้ทำได้
//
// เส้นโค้งนี้ให้ 60 ที่เส้นตายพอดี ดิ่งเร็วในวันแรก แล้วค่อย ๆ แบนออกไป
//   เหลือ 1 ชม. → 53 · 5 ชม. → 42 · 1 วัน → 28 · 3 วัน → 17 · 1 สัปดาห์ → 8
function urgencyScore(effHours) {
  return Math.max(2, Math.round(60 - 7 * Math.log2(1 + Math.max(0, effHours))));
}

function priorityInfo(task, now = new Date()) {
  const reasons = [];
  let score = 0;

  const due = task.due ? new Date(task.due) : null;
  const hoursLeft = due ? (due - now) / 3.6e6 : null;
  const type = taskType(task);
  const ti = TASK_TYPES[type];

  // สอบต้องเริ่มอ่านล่วงหน้า จึงให้เวลาที่เหลือ "เดินเร็วกว่าจริง" ตาม prepHours
  // เดิมใช้การลบ (hoursLeft − 48) ซึ่งพอใกล้วันสอบจะติดลบ ต้องมีสาขาพิเศษมารับ
  // และทำให้สอบอีก 47 ชม. ได้คะแนนเท่างานที่ส่งในอีกนาทีเดียว — หารแทน เส้นจึงต่อเนื่องตลอด
  const effHours = hoursLeft == null ? null : hoursLeft / (1 + ti.prepHours / 24);

  if (due) {
    if (type === 'activity' || type === 'reminder') {
      // เหตุการณ์ตามเวลา: ไม่ต้องเจียดเวลาทำล่วงหน้า ความด่วนพุ่งเฉพาะตอนใกล้ถึงเวลา
      if (hoursLeft < 0)        { score += 30; reasons.push('⚠ เลยเวลาแล้ว'); }
      else if (hoursLeft <= 3)  { score += 55; reasons.push('อีก ' + Math.max(1, Math.round(hoursLeft)) + ' ชม. ถึงเวลา'); }
      else if (hoursLeft <= 14) { score += 38; reasons.push('ถึงเวลาวันนี้'); }
      else if (hoursLeft <= 30) { score += 24; reasons.push('ถึงเวลาพรุ่งนี้'); }
      else                      { score += 6;  reasons.push('ยังอีกหลายวัน'); }
    } else if (hoursLeft < 0) {
      // เลยกำหนดต้องอยู่เหนือสุดของเส้นโค้ง (60) เสมอ ไม่งั้นงานที่พลาดไปแล้วจะหล่นหาย
      score += 65; reasons.push('⚠ เลยกำหนดแล้ว');
    } else {
      score += urgencyScore(effHours);
      // คะแนนมาจากเส้นโค้ง แต่ข้อความต้องพูดแบบที่คนนับวันกันจริง
      //
      // เดิมแบ่งด้วยจำนวนชั่วโมง ซึ่งไม่ตรงกับปฏิทินที่ผู้ใช้มองอยู่:
      // งานที่ส่งพรุ่งนี้ 23:59 เหลือ 30 ชั่วโมง แล้วได้ข้อความว่า "ส่งใน 2 วัน"
      // ทั้งที่บรรทัดถัดไปบนการ์ดใบเดียวกันเขียนว่า "ส่งพรุ่งนี้" — จอเดียวพูดสองอย่าง
      const dayDiff = Math.round((atTime(due, 0, 0) - atTime(now, 0, 0)) / 864e5);
      if (hoursLeft <= 6)  { reasons.push(ti.verb + 'ภายใน ' + Math.max(1, Math.round(hoursLeft)) + ' ชม.'); }
      else if (dayDiff <= 0) { reasons.push(ti.verb + 'วันนี้'); }
      else if (dayDiff === 1) { reasons.push(ti.verb + 'พรุ่งนี้'); }
      else if (type === 'exam' && hoursLeft <= ti.prepHours) {
        reasons.push('สอบใน ' + Math.max(1, Math.round(hoursLeft / 24)) + ' วัน — ควรเริ่มอ่านแล้ว');
      }
      else if (dayDiff <= 6) { reasons.push(ti.verb + 'ใน ' + dayDiff + ' วัน'); }
      else                   { reasons.push('ยังพอมีเวลา'); }
    }
  } else { score += 14; reasons.push('ยังไม่ระบุกำหนด'); }

  // คะแนนเก็บบอก "เสียหายแค่ไหนถ้าไม่ทำ" ซึ่งไม่ใช่เรื่องเดียวกับความด่วน จึงต้องเบากว่าเสมอ
  // ของเดิมให้ได้ถึง 30 = เท่ากับความต่างของแถบความด่วนทั้งแถบ และให้ค่าว่าง = 0
  // แปลว่า "ครูไม่ได้บอกว่ากี่คะแนน" ถูกอ่านเป็น "ไม่สำคัญ" — ซึ่งเป็นกรณีปกติของนักเรียน
  if (task.scorePct != null) {
    score += Math.min(15, Math.round(task.scorePct / 2));
    reasons.push('คะแนน ' + task.scorePct + '%');
  } else {
    score += 6;   // ค่ากลาง ≈ งาน 12% · ไม่รู้ ≠ ไม่สำคัญ (ไม่ต้องมีเหตุผลกำกับ ไม่มีอะไรจะบอก)
  }

  // เวลาที่ใช้ทำมีความหมายเฉพาะงานที่ต้องนั่งทำ — กิจกรรมไม่ต้องเจียดเวลา
  //
  // ขนาดงานถูกลดน้ำหนักครึ่งหนึ่งเมื่อเส้นตายยังอยู่ไกลกว่าสองวัน
  //
  // เหตุผล: "งานใหญ่ควรเริ่มก่อน" เป็นความจริง แต่มันเป็นความจริงข้อเดียวกับที่ prepHours
  // พูดไปแล้วสำหรับการสอบ — ให้เต็มทั้งสองที่คือการนับซ้ำ และผลของการนับซ้ำวัดได้จริง:
  // สอบอีกเจ็ดวันที่ต้องอ่านสองชั่วโมง (19+15+15=49) แซงการบ้านมีคะแนนที่ส่งพรุ่งนี้ (25+10+9=44)
  // แล้วการ์ด "ทำสิ่งนี้ก่อน" ก็ชี้ไปที่การอ่านสอบ ส่วนการบ้านตกไปอยู่ในกล่อง "ยังไม่ต้องคิดตอนนี้"
  // ซึ่งเป็นความผิดแบบเดียวกับบั๊ก M1 ที่เคยแก้ไปแล้ว แค่มาทางขนาดงานแทนทางโบนัสสอบ
  //
  // งานใหญ่ที่ยังไกลไม่ได้หายไปไหน — planner.js แบ่งให้มันได้ที่ในแผนของทุกวันอยู่แล้ว
  // มันแค่ไม่ควรชนะงานที่พรุ่งนี้ต้องส่ง
  if (ti.schedulable) {
    const need = remainingMin(task);
    const far = hoursLeft != null && hoursLeft > 48;
    const w = far ? 0.5 : 1;
    if (need >= 90)      { score += 15 * w; reasons.push((type === 'exam' ? 'อ่าน' : 'งานใหญ่') + ' ~' + Math.round(need / 60 * 10) / 10 + ' ชม. — ควรเริ่มก่อน'); }
    else if (need >= 45) { score += 9 * w;  reasons.push('ใช้เวลา ~' + need + ' นาที'); }
    else                 { score += 4 * w;  reasons.push('~' + need + ' นาที'); }
    score = Math.round(score);
  }

  // ชั้นที่สอง: ความสำคัญบอกว่า "งานไหนใหญ่กว่า" แต่ไม่ได้บอกว่า "งานไหนหมดโอกาสก่อน"
  //
  // สอบกลางภาค 30% สองชั่วโมง สำคัญกว่าใบงาน 10% หนึ่งชั่วโมงจริง — แต่สอบยังมีวันพรุ่งนี้
  // ส่วนใบงานที่ส่งพรุ่งนี้เช้าไม่มีวันพรุ่งนี้ให้แล้ว งานที่หมดโอกาสก่อนต้องได้ทำก่อน
  //
  // ตรรกะนี้ต้องอยู่ในคะแนน ไม่ใช่อยู่แค่ในตัวจัดแผน ไม่งั้นการ์ด "ควรทำก่อน" บนหน้าแรก
  // จะชี้ไปคนละงานกับที่หน้าแผนบอก — แอปที่เถียงกันเองคือแอปที่ไม่มีใครเชื่อ
  const lastChance = isLastChanceToday(task, now);
  if (lastChance) {
    score += 18;
    reasons.unshift('วันนี้เป็นโอกาสสุดท้ายที่จะทำทัน');
  }

  // เพดานใหม่ ≈ 95 (เลยกำหนด 65 + คะแนน 15 + งานใหญ่ 15) — ขีดแบ่งดาวจึงต้องเลื่อนตาม
  // ป้าย "ด่วนมาก" ที่ติดครึ่งรายการคือป้ายที่ไม่ได้บอกอะไรเลย
  let stars = score >= 52 ? 5 : score >= 44 ? 4 : score >= 32 ? 3 : score >= 22 ? 2 : 1;

  // ผู้ใช้กำหนดความสำคัญเอง → เคารพการตัดสินใจของเขา (override AI)
  // ลำดับภายในดาวเท่ากัน: ใกล้ deadline กว่ามาก่อน
  if (task.userStars >= 1) {
    stars = task.userStars;
    score = task.userStars * 20
      + (hoursLeft != null ? Math.max(0, 15 - Math.max(0, hoursLeft) / 12) : 0);
    reasons.unshift('★ กำหนดความสำคัญเอง');
  }
  const urgency = (hoursLeft != null && hoursLeft < 0) ? 'over'
    : (hoursLeft != null && hoursLeft <= 30) ? 'hot'
    : (hoursLeft != null && hoursLeft <= 54) ? 'mid' : 'norm';

  return { score, stars, reasons, hoursLeft, urgency, lastChance, type, typeInfo: ti };
}

// คิดคะแนนใบละครั้งแล้วค่อยเรียง — ของเดิมเรียกซ้ำในตัวเปรียบเทียบ กลายเป็น 2·n·log n ครั้ง
// ตอนที่คะแนนยังเป็นเลขคณิตล้วนก็พอทน แต่ตอนนี้มันต้องไปไล่ช่องว่างของอาทิตย์หน้าด้วย
function sortByPriority(tasks, now = new Date()) {
  return tasks
    .map(t => ({ t, s: priorityInfo(t, now).score }))
    .sort((a, b) => b.s - a.s)
    .map(x => x.t);
}

