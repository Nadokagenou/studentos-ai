-- ตรวจ production (อ่านอย่างเดียว): cleanup_integrations() เป็น security definer ที่ลบแถวในทะเบียนตัวเชื่อม
-- ของทุกบัญชี แต่ anon และ authenticated สั่งรันได้ (ค่าปริยายของ Postgres ให้ PUBLIC execute)
-- มันถูกออกแบบให้ pg_cron เรียกอย่างเดียว · ไม่มีหน้าจอไหนในแอปเรียก
-- ตัวที่ลบได้ตอนนี้คือแถวที่ปิดไปแล้วเกิน 90 วันเท่านั้น จึงยังไม่เคยเสียหาย — แต่ฟังก์ชันที่แตะข้อมูลของทุกคน
-- ต้องไม่เปิดให้คนนอกเรียก ไม่ว่ามันจะทำอะไรอยู่วันนี้
--
-- pg_cron รันในนามเจ้าของ job (postgres) ซึ่งเป็นเจ้าของฟังก์ชันด้วย จึงไม่โดนผลของ revoke นี้
-- ============================================================

revoke all on function public.cleanup_integrations() from public, anon, authenticated;
