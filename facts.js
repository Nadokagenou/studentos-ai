// ---------- วิชาที่ความรู้ทบต้น ----------
// ไม่อ่านฟิสิกส์บทนี้ ไม่ได้เสียแค่คะแนนสอบครั้งนี้ — มันทำให้อีกสามบทข้างหน้าอ่านยากขึ้น
// วิชาที่แยกเป็นหน่วยจบในตัว (ประวัติศาสตร์ · ศิลปะ · การงาน) ไม่มีหนี้ก้อนนี้
const FACT_CUMULATIVE = [
  'คณิตศาสตร์', 'ฟิสิกส์', 'เคมี', 'ชีววิทยา', 'วิทยาศาสตร์',
  'ภาษาอังกฤษ', 'ภาษาไทย', 'วิทยาการคำนวณ',
];

// ---------- วิชาที่ต้องต่อความคิด ----------
// "ต่อความคิด" ไม่เท่ากับ "ยาก" — วาดรูปสามชั่วโมงไม่ได้พังเพราะถูกขัดจังหวะ
// แต่โจทย์เลขที่คิดค้างไว้ครึ่งข้อ พอถูกขัดแล้วต้องเริ่มไล่ใหม่
const FACT_DEEP_SUBJECTS = ['คณิตศาสตร์', 'ฟิสิกส์', 'เคมี', 'วิทยาการคำนวณ', 'ภาษาอังกฤษ'];

// คำในเนื้องานที่ชี้ระดับการต่อความคิดได้ชัดกว่าชื่อวิชา
// (วิชาศิลปะที่สั่งให้ "เขียนรายงาน" ต่อความคิดกว่าวิชาเลขที่สั่งให้ "ปริ้นใบงานมาส่ง")
const FACT_DEEP_WORDS = /โจทย์|พิสูจน์|คำนวณ|เขียนโปรแกรม|เขียนเรียงความ|เรียงความ|essay|วิเคราะห์|แต่งกลอน/i;
const FACT_SHALLOW_WORDS = /ปริ้น|พิมพ์ส่ง|เตรียมของ|ซื้อ|ถ่ายเอกสาร|ส่งไฟล์|เซ็นชื่อ|กรอกแบบ|ระบายสี|ตัดกระดาษ/i;

// ---------- งานที่ติดคนอื่น ----------
const FACT_PARTNER_WORDS = /กลุ่ม|เป็นคู่|จับคู่|ทีม|group|pair|ร่วมกับเพื่อน/i;

// ---------- ครูรับงานสายไหม ----------
// ค่าเริ่มต้นของการบ้านไทยคือ "รับแต่หัก" ไม่ใช่ "ไม่รับ" — ตั้งเป็นไม่รับทั้งหมดเมื่อไหร่
// เอนจินจะตีราคาการบ้านที่ส่งช้าได้เท่ากับการขาดสอบ ซึ่งทำให้มันเตือนแรงเกินจริงตลอดเวลา
const FACT_NOLATE_WORDS = /ไม่รับงานสาย|ปิดระบบ|ไม่รับย้อนหลัง|หมดเขตคือหมดเขต|ส่งช้าไม่รับ/i;
const FACT_OKLATE_WORDS = /ส่งเมื่อไหร่ก็ได้|ไม่มีกำหนดตายตัว|ตามสะดวก/i;

function factText(task) {
  return [task.detail, task.note, task.raw, task.subject].filter(Boolean).join(' ');
}

// ---------- ตัวหลัก ----------
// คืนค่าที่ "ตัดสินใจได้เลย" เสมอ · ค่าที่ผู้ใช้ระบุไว้บนงานชนะค่าที่เดาทุกกรณี
// ฟิลด์บนงานเป็น undefined = ยังไม่เคยมีใครแตะ ไม่ใช่ "ตั้งใจให้ว่าง"
function taskFacts(task) {
  if (!task) return null;
  const txt = factText(task);
  const subj = (task.subject || '').trim();
  const type = typeof taskType === 'function' ? taskType(task) : (task.type || 'homework');

  // ---- ต้องต่อความคิดแค่ไหน ----
  let load = task.cognitiveLoad;
  if (!load) {
    if (FACT_SHALLOW_WORDS.test(txt)) load = 'shallow';
    else if (FACT_DEEP_WORDS.test(txt) || FACT_DEEP_SUBJECTS.includes(subj)) load = 'deep';
    else load = 'medium';
  }

  // ---- ส่งช้าแล้วเกิดอะไร ----
  // ข้อสอบไม่มีรอบสองเสมอ ไม่ว่าครูจะใจดีแค่ไหน — ข้อนี้ไม่ให้เดาจากข้อความ
  let late = task.latePolicy;
  if (!late) {
    if (type === 'exam' || type === 'activity') late = 'zero';
    else if (FACT_NOLATE_WORDS.test(txt)) late = 'zero';
    else if (FACT_OKLATE_WORDS.test(txt)) late = 'ok';
    else late = 'penalty';
  }

  return {
    cumulative: task.cumulative != null ? !!task.cumulative : FACT_CUMULATIVE.includes(subj),
    cognitiveLoad: load,
    deep: load === 'deep',
    latePolicy: late,
    partnerDependent: task.partnerDependent != null
      ? !!task.partnerDependent : FACT_PARTNER_WORDS.test(txt),
    blockedBy: Array.isArray(task.blockedBy) ? task.blockedBy.filter(Boolean) : [],
  };
}

// ---------- ราคาของการส่งช้า ----------
// สัดส่วนของคะแนนที่ยัง "กู้คืนได้" ถ้าส่งช้า — 0 แปลว่ากู้ไม่ได้เลย
//
// ตัวเลขนี้คือจุดที่ของเดิมพลาดแบบเงียบที่สุด: `loss.js` คิดว่าทุกอย่างที่ไม่เสร็จ
// ตอนถึงกำหนด = เสียคะแนนส่วนนั้นทั้งก้อน ซึ่งจริงกับข้อสอบ แต่ไม่จริงกับใบงาน
// ที่ครูหักสิบเปอร์เซ็นต์ต่อวัน · ผลคือเอนจินเตือนเรื่องใบงานแรงพอ ๆ กับเรื่องสอบ
const FACT_LATE_RECOVER = { zero: 0, penalty: 0.7, ok: 0.9 };

function latePolicyRecover(policy) {
  return FACT_LATE_RECOVER[policy] != null ? FACT_LATE_RECOVER[policy] : 0;
}

